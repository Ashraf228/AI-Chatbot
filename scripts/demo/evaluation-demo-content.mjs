export function renderDemoArticle(articleItem) {
  return [
    DEMO_NOTICE,
    '',
    `Titel: ${articleItem.title}`,
    `Zusammenfassung: ${articleItem.summary}`,
    '',
    'Lösungsschritte:',
    ...articleItem.steps.map((step, index) => `${index + 1}. ${step}`),
    '',
    `Mögliche Rückfrage: ${articleItem.followUp}`,
    `Eskalationskriterium: ${articleItem.escalation}`,
  ].join('\n');
}
